/** How the novel handles a real event. */
export type Treatment =
  | 'preserved' // happens as it really did
  | 'altered' // happens, with a different course or outcome
  | 'prevented' // does not happen
  | 'moved' // happens at a different time
  | 'ahead'; // later than the volumes mapped so far

export const TREATMENT_LABEL: Record<Treatment, string> = {
  preserved: 'Preserved in the novel',
  altered: 'Altered in the novel',
  prevented: 'Prevented in the novel',
  moved: 'Moved in time',
  ahead: 'Beyond Vol. 5',
};

/** A real-world event shown in the history lane above the cards. */
export interface RealEventRecord {
  id: string;
  /** ISO date. With `precision: 'month'` the day is a placeholder. */
  date: string;
  precision?: 'month';
  title: string;
  /** What really happened. */
  real: string;
  /** What the novel does with it. May carry spoiler markers (see lib/spoilers.ts). */
  novel: string;
  treatment: Treatment;
  /** Ids of the timeline events that answer it. The entry is shown once the earliest of them has been read. */
  counterparts?: string[];
  /** Shown with a label before its neighbours when space is short. */
  major?: boolean;
}

